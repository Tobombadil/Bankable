def extract_member(zip_path: pathlib.Path, member: str, dest: pathlib.Path) -> pathlib.Path:
    """Stream one member out of the zip (the monthly rasters, 12 x 64 MB, are never extracted)."""
    with zipfile.ZipFile(zip_path) as z:
        name = next((n for n in z.namelist() if n.endswith(member) and not n.startswith("__MACOSX")), None)
        if name is None:
            raise FileNotFoundError(f"{member} not in {zip_path.name}")
        with z.open(name) as src, dest.open("wb") as dst:
            shutil.copyfileobj(src, dst, 1 << 20)
    return dest


def build_layer(
    layer_id: str,
    tif: pathlib.Path,
    *,
    bbox: tuple[float, float, float, float],
    out_dir: pathlib.Path,
    source_url: str,
    retrieved_at: str,
) -> dict[str, Any]:
    grid, stats = read_scaled(tif, bbox, scale=SCALE, invalid=0.0)
    prov = provenance_for(
        SOURCE_ID,
        source_url=source_url,
        retrieved_at=retrieved_at,
        licence=LICENCE_NAME,
        vintage=VINTAGE,
        notice=NOTICE,
    )
    out = out_dir / f"{layer_id}.tif"
    summary = write_quantised(
        grid, out, scale=SCALE, provenance=prov, stats=stats, extra_metadata={"citation": CITATION}
    )
    return {
        "layer_id": layer_id,
        "file": out.name,
        "kind": "raster",
        "provenance": {**prov.record(), "citation": CITATION},
        "licence_name": LICENCE_NAME,
        "summary": summary,
    }


def build(
    *,
    region: str = "texas",
    out_dir: pathlib.Path | None = None,
    snapshot_dir: pathlib.Path | None = None,
    session: PoliteSession | None = None,
    store: Store | None = None,
    work_dir: pathlib.Path | None = None,
) -> list[dict[str, Any]]:
    """Both layers for `region`. With `snapshot_dir`, read the zips (or the extracted annual tifs) from
    there instead of fetching; otherwise fetch, extract the annual raster, and delete both raw files."""
    bbox = REGIONS[region]
    out_dir = output_dir(out_dir)
    log = FetchLog(SOURCE_ID)
    session = session or PoliteSession()
    if snapshot_dir is None:
        verify_terms(session, TERMS_URL, TERMS_PHRASES, log=log)
    outputs = []
    with tempfile.TemporaryDirectory(dir=work_dir) as tmp:
        tmpdir = pathlib.Path(tmp)
        for layer_id, (zip_name, member) in FILES.items():
            url = f"{BASE_URL}/{zip_name}"
            retrieved_at = now_iso()
            tif_name = pathlib.Path(member).name
            if snapshot_dir is not None:
                tif = snapshot_dir / tif_name
                if not tif.exists():
                    retrieved_at = snapshot_time(snapshot_dir / zip_name)
                    tif = extract_member(snapshot_dir / zip_name, member, tmpdir / tif_name)
                else:
                    retrieved_at = snapshot_time(tif)
            else:
                zpath = tmpdir / zip_name
                info = download(session, url, zpath, log=log)
                retrieved_at = info["retrieved_at"]
                tif = extract_member(zpath, member, tmpdir / tif_name)
                zpath.unlink()
            outputs.append(
                build_layer(
                    layer_id, tif, bbox=bbox, out_dir=out_dir, source_url=url, retrieved_at=retrieved_at
                )
            )
            if snapshot_dir is None or tif.parent == tmpdir:
                tif.unlink()
    log.write(store if snapshot_dir is None else None, region=region, layers=[o["layer_id"] for o in outputs])
    return outputs


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--region", choices=sorted(REGIONS), default="texas")
    parser.add_argument("--snapshot-dir", type=pathlib.Path)
    parser.add_argument("--out-dir", type=pathlib.Path)
    args = parser.parse_args(argv)
    t0 = time.monotonic()
    outputs = build(region=args.region, out_dir=args.out_dir, snapshot_dir=args.snapshot_dir, store=Store())
    print(json.dumps({"layers": outputs, "elapsed_s": round(time.monotonic() - t0, 2)}))  # noqa: T201


if __name__ == "__main__":
    main()
